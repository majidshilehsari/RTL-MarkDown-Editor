export const detectLang = () => {
  if (typeof navigator === 'undefined') return 'fa';
  const n = (navigator.language || 'fa').toLowerCase();
  if (n.startsWith('fa') || n.startsWith('pr')) return 'fa';
  if (n.startsWith('ar')) return 'ar';
  return 'en';
};

